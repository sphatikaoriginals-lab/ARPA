# Non-drug junk words generated by PDF headers/footers
JUNK_PATTERNS = [
    r"^page\s*\d+",
    r"^s\.?\s*no",
    r"^government\s+of\s+india",
    r"^central\s+drugs",
    r"^cdsco",
    r"^dated",
    r"^circular",
    r"^notice",
    r"^directorate\s+general",
    r"^fda",
    r"^ministry\s+of",
    r"^new\s+delhi",
    r"^\d+$",               # Pure numbers
    r"^[a-zA-Z]$",          # Single letter entries
    r"^[\W_]+$"             # Pure punctuation
]

def clean_and_repair_database():
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()

    print("[*] Starting ARPA Database Deep Clean & Error Filtering...")

    # 1. Fetch total rows before cleaning
    cursor.execute("SELECT COUNT(*) FROM salt_cache")
    total_before = cursor.fetchone()[0]
    print(f"[*] Total entries before cleaning: {total_before}")

    # 2. Delete Junk / Header-Footer rows
    deleted_junk = 0
    for pattern in JUNK_PATTERNS:
        cursor.execute("SELECT brand_name FROM salt_cache")
        all_brands = cursor.fetchall()
        for (b_name,) in all_brands:
            if b_name and re.search(pattern, b_name.strip(), re.IGNORECASE):
                cursor.execute("DELETE FROM salt_cache WHERE brand_name = ?", (b_name,))
                deleted_junk += 1

    print(f"[*] Deleted {deleted_junk} non-drug junk/header rows.")

    # 3. Clean and fix concatenated text in 'salts' JSON (e.g. 'NimesulideTizanidine')
    cursor.execute("SELECT brand_name, salts FROM salt_cache")
    rows = cursor.fetchall()
    fixed_salts_count = 0

    for brand_name, salts_raw in rows:
        try:
            salts = json.loads(salts_raw)
            if isinstance(salts, list):
                new_salts = []
                modified = False
                for s in salts:
                    # Split PascalCase concatenation like 'NimesulideTizanidine' -> 'Nimesulide Tizanidine'
                    fixed_s = re.sub(r'([a-z])([A-Z])', r'\1 \2', s)
                    if fixed_s != s:
                        modified = True
                    new_salts.append(fixed_s.strip())
                
                if modified:
                    cursor.execute("UPDATE salt_cache SET salts = ? WHERE brand_name = ?", (json.dumps(new_salts), brand_name))
                    fixed_salts_count += 1
        except Exception:
            continue

    print(f"[*] Fixed {fixed_salts_count} concatenated/malformed salt entries.")

    # 4. Inject & Lock Verified Standard Master Mappings
    print("[*] Locking verified Golden Standard mappings...")
    for brand, salts in VERIFIED_CORRECTIONS.items():
        cursor.execute("DELETE FROM salt_cache WHERE brand_name = ?", (brand,))
        cursor.execute("INSERT OR REPLACE INTO salt_cache (brand_name, salts) VALUES (?, ?)", (brand, json.dumps(salts)))

    conn.commit()

    # 5. Optimize & Defragment Database
    cursor.execute("VACUUM")
    cursor.execute("PRAGMA optimize")
    conn.commit()

    cursor.execute("SELECT COUNT(*) FROM salt_cache")
    total_after = cursor.fetchone()[0]
    conn.close()

    print(f"[✓] Database Sanitization Complete!")
    print(f"[✓] Clean, Valid Formulations Remaining: {total_after}")

if __name__ == "__main__":
    clean_and_repair_database()